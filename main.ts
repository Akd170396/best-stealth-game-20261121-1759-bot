// Hand-in program for the make.fun best stealth game bounty (Node 22, standard library only).
// The game itself lives in game/ as plain static files a desktop browser loads offline.
// This program copies game/ and screenshots/ from beside itself to /output (or
// MAKEFUN_OUTPUT_DIR when run outside the grader) and writes /output/dossier.json with
// buildDossier from the kit's vendor/makefun-game.ts, using the scorer's own caps so the
// entry it writes is one the scorer accepts. It writes the same bytes on every run.

import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-game.ts';

const repoDir = fileURLToPath(new URL('.', import.meta.url));
const outDir = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';

mkdirSync(outDir, { recursive: true });
cpSync(join(repoDir, 'game'), join(outDir, 'game'), { recursive: true });
mkdirSync(join(outDir, 'screenshots'), { recursive: true });
if (existsSync(join(repoDir, 'screenshots'))) {
  cpSync(join(repoDir, 'screenshots'), join(outDir, 'screenshots'), { recursive: true });
}

const dossier = buildDossier(outDir, {
  text_max_bytes: 163840,
  screenshots: { max: 4, max_bytes: 262144 },
  game_max_files: 993,
  game_max_bytes: 50331648,
  game_path_max_bytes: 1000,
});
writeFileSync(join(outDir, 'dossier.json'), dossier);
